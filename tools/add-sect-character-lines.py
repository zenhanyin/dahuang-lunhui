def update_workbook(path: Path) -> None:
    wb = load_workbook(path)
    ws = wb["Choices"]
    headers = [cell.value for cell in ws[1]]
    idx = {name: headers.index(name) + 1 for name in headers if name}

    for row in range(2, ws.max_row + 1):
        key = (ws.cell(row, idx["Act"]).value, ws.cell(row, idx["Order"]).value)
        if key not in UPDATES:
            continue
        text, log = UPDATES[key]
        ws.cell(row, idx["Text"]).value = text
        ws.cell(row, idx["Log"]).value = log

    wb.save(path)
    print(f"updated character lines in {path}")


for workbook in WORKBOOKS:
    update_workbook(workbook)
